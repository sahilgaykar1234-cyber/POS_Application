#!/usr/bin/env python3
"""Builds lib/core/i18n/strings_<lang>.dart from tools/i18n/translations_*.tsv.

    python3 tools/i18n/build_catalogs.py          # build + report
    python3 tools/i18n/build_catalogs.py --check  # exit 1 if any key is missing

Each TSV row: english<TAB>hi<TAB>gu<TAB>mr   (\\n = new line).
Reports app keys (tr('...') in lib/) that have no translation yet.
"""
import glob, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LANGS = ['hi', 'gu', 'mr']
# Not words: never need a translation.
IGNORE = {'T{0}', 'J', 'V-{0}'}


def unesc(s):
    return s.replace('\\n', '\n')


def dart_lit(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def load():
    rows = {}
    for path in sorted(glob.glob(os.path.join(ROOT, 'tools/i18n/translations_*.tsv'))):
        for n, line in enumerate(open(path, encoding='utf-8').read().split('\n')[1:], 2):
            if not line.strip():
                continue
            cols = line.split('\t')
            if len(cols) != 4:
                sys.exit(f'{path}:{n}: expected 4 columns, got {len(cols)}')
            en = unesc(cols[0])
            if en in rows:
                print(f'note: duplicate {en!r} ({path}:{n})')
            rows[en] = [unesc(c) for c in cols[1:]]
    return rows


def app_keys():
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'tools/i18n/wrap_strings.py'), 'keys'], capture_output=True, text=True, check=True).stdout
    import json
    return set(json.loads(out))


def main():
    rows = load()
    bad = 0
    for en, tr in rows.items():
        ph = set(re.findall(r'\{\d+\}', en))
        for lang, t in zip(LANGS, tr):
            extra = set(re.findall(r'\{\d+\}', t)) - ph
            if extra:
                print(f'error: {lang} {en!r} has unknown placeholders {extra}')
                bad += 1
            if not t.strip() and en.strip():
                print(f'error: {lang} {en!r} is empty')
                bad += 1
    for i, lang in enumerate(LANGS):
        body = ''.join(f'  {dart_lit(en)}: {dart_lit(tr[i])},\n' for en, tr in sorted(rows.items()))
        path = os.path.join(ROOT, f'lib/core/i18n/strings_{lang}.dart')
        open(path, 'w', encoding='utf-8').write(
            f'// GENERATED by tools/i18n/build_catalogs.py from tools/i18n/translations_*.tsv. Do not edit.\n'
            f'// ignore_for_file: lines_longer_than_80_chars\n'
            f'const Map<String, String> k{lang.capitalize()} = {{\n{body}}};\n')
    missing = sorted(k for k in app_keys() - set(rows) - IGNORE)
    for k in missing:
        print('missing:', repr(k))
    print(f'{len(rows)} translations, {len(missing)} missing')
    if bad or ('--check' in sys.argv and missing):
        sys.exit(1)


if __name__ == '__main__':
    main()
